-- восстановить его из данных статьи невозможно.
--
-- Хранится рядом с article_path и html_path: это такой же результат обработки статьи,
-- и живёт он ровно столько же — до очистки статьи каскадом от articles.
--
-- NULL означает «промпт ещё не публиковался или публикация не удалась». Раздел в
-- result.md при этом остаётся на месте, но с пустым значением.
-- =============================================================================

ALTER TABLE article_outputs
    ADD COLUMN IF NOT EXISTS google_doc_url TEXT;
