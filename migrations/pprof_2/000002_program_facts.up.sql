-- =============================================================================
-- Числа программы в article_inputs: hours, duration, price, document, attestation.
--
--   docker exec -i seo-postgres psql -U seo -d seo \
--     -v ON_ERROR_STOP=1 -c 'SET search_path TO pprof_2' -f - \
--     < migrations/pprof_2/000002_program_facts.up.sql
--
-- Зачем колонки. Объём, срок, стоимость, документ по итогам и форма аттестации стоят на
-- странице дважды: в тексте, который пишет модель, и в полях записи, которые человек
-- заполняет руками. До этой миграции в книге их не было вовсе, и промпт выводил их из вида
-- программы диапазонами («ПК — от 16, типично 72–144 ак. часа»). Диапазон с полем записи не
-- сверить: расхождение видно только глазами на самой странице, и на площадке оно уже
-- случилось — «150 часов» в тексте против «144 часа» в плашке темы.
--
-- Источник один и он человеческий: колонка книги. Тот же набор колонок и с тем же смыслом
-- заведён у obuch_2 (migrations/obuch_2/000001_schema.up.sql) — площадки разные, а поле одно
-- и то же, и второго имени для него быть не должно.
--
-- Все пять nullable и пустые по умолчанию: это прежнее поведение. Незаполненная колонка
-- означает «значения нет», и промпт на такое значение параметр на страницу не выводит, а
-- строит фактуру по правилам вида программы — ровно как до миграции. Поэтому сорока с лишним
-- страницам, уже импортированным и опубликованным, миграция ничего не ломает.
-- =============================================================================

ALTER TABLE article_inputs
    ADD COLUMN IF NOT EXISTS hours TEXT,
    ADD COLUMN IF NOT EXISTS duration TEXT,
    ADD COLUMN IF NOT EXISTS price TEXT,
    ADD COLUMN IF NOT EXISTS document TEXT,
    ADD COLUMN IF NOT EXISTS attestation TEXT;

COMMENT ON COLUMN article_inputs.hours IS
    'Объём программы в академических часах. Пусто — параметра на странице нет.';
COMMENT ON COLUMN article_inputs.duration IS
    'Срок обучения. Пусто — параметра на странице нет.';
COMMENT ON COLUMN article_inputs.price IS
    'Стоимость. Пусто — цену на странице не называют вовсе.';
COMMENT ON COLUMN article_inputs.document IS
    'Документ по итогам обучения. Пусто — вид документа выводится из вида программы.';
COMMENT ON COLUMN article_inputs.attestation IS
    'Форма итоговой аттестации. Пусто — параметра на странице нет.';
