-- =============================================================================
-- article_inputs.seo_title — короткий заголовок для поисковой выдачи.
--
--   docker exec -i seo-postgres psql -U seo -d seo \
--     -v ON_ERROR_STOP=1 -c 'SET search_path TO pprof_1' -f - \
--     < migrations/pprof_1/000002_seo_title.up.sql
--
-- Зачем отдельная колонка, а не переписанный article_name. Название статьи уходит в два
-- места сразу: post_title записи и _yoast_wpseo_title. Первое человек читает в админке и в
-- списке записей, и там длинное описательное название полезно; второе показывает поиск, и
-- он режет его примерно на 60 знаках. Одной строкой две задачи не закрыть: в книге из 85
-- статей за порогом оказались 56 названий, а укоротить их все значило бы потерять смысл
-- там, где он нужен человеку.
--
-- Колонка nullable и пустая по умолчанию: это прежнее поведение. Пустой seo_title означает
-- «в выдачу идёт название статьи», ровно как было до появления колонки, — поэтому старым
-- статьям миграция ничего не ломает, а task_1 колонки не заводит вовсе.
--
-- Имя то же, что у pprof_2 (migrations/pprof_2/000001_schema.up.sql:125), и значение то же:
-- второго имени для одного и того же поля заводить нельзя.
-- =============================================================================

ALTER TABLE article_inputs
    ADD COLUMN IF NOT EXISTS seo_title TEXT;

COMMENT ON COLUMN article_inputs.seo_title IS
    'Короткий заголовок для поисковой выдачи (_yoast_wpseo_title). Пусто — идёт title статьи.';
