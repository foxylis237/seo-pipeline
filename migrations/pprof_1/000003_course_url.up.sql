-- =============================================================================
-- article_inputs.course_url — адрес, на который ведёт кнопка карточки призыва.
--
--   docker exec -i seo-postgres psql -U seo -d seo \
--     -v ON_ERROR_STOP=1 -c 'SET search_path TO pprof_1' -f - \
--     < migrations/pprof_1/000003_course_url.up.sql
--
-- Статья блога заканчивается карточкой учебного центра с кнопкой «Записаться на обучение».
-- Кнопка ведёт в деньги, и решать, куда уходит читатель, обязан человек, а не модель: адрес
-- приходит книгой, как у obuch_1 (migrations/obuch_1/000002_course_url.up.sql). Имя то же и
-- значение то же — второго имени для одного поля заводить нельзя.
--
-- Значение — страница программы или, если своей программы у темы нет, страница рубрики
-- площадки. Колонка nullable по форме, но обязательна по смыслу: пустое значение роняет
-- статью до первого сообщения модели (pprof1.Flow). NULL означает ровно одно — колонки не
-- было в схеме, когда статью импортировали; такие значения дозаполняет повторный import.
-- =============================================================================

ALTER TABLE article_inputs
    ADD COLUMN IF NOT EXISTS course_url TEXT;

COMMENT ON COLUMN article_inputs.course_url IS
    'Адрес программы или рубрики для кнопки карточки призыва. Пусто — статья не генерируется.';
