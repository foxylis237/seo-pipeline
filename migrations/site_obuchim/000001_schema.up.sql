-- =============================================================================
-- Схема site_obuchim — каталог услуг площадки obuchim-specialista.ru.
--
-- Вторая площадка проекта и второй каталог. Таблицы те же, что у site: схема каталога
-- описывает не площадку, а то, что мы о любой площадке храним, — и расхождение здесь
-- означало бы, что подбор услуг у двух сайтов работает по-разному.
--
-- ВАЖНО: схема НЕ принадлежит ни одной задаче и применяется руками, как и остальные:
--
--   docker exec -i seo-postgres psql -U seo -d seo -v ON_ERROR_STOP=1 \
--     -f - < migrations/site_obuchim/000001_schema.up.sql
--
-- Почему отдельная схема, а не колонка площадки в site: сбор начинается с
-- `DELETE FROM <схема>.programs`, и один забытый `WHERE site = ...` стёр бы каталог соседа
-- молча — а сломалось бы это не у той задачи, что запускала сбор, а у чужих статей.
-- Имя схемы приходит из профиля задачи через composition root и в запрос подставляется
-- обязательным параметром конструктора: «по умолчанию site» здесь невыразимо.
--
-- Что здесь есть и чего нет: то же, что у соседа, — идентификатор записи, адрес, название,
-- рубрика сайта и наша профессия. Фактов о программе (цена, срок, документ) здесь нет.
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS site_obuchim;


-- =============================================================================
-- Рубрика сайта: то, чем площадка сама разложила свои услуги.
--
-- Приходит полем terms того же wp.getPosts, которым читается каталог, — своей выдумки
-- здесь нет ни одной строки. У этой площадки рубрики дробные: 184 термина на 1528 услуг,
-- медиана — четыре программы на рубрику, крупных всего две («Аппаратчики и автоклавщики»
-- 166 и «Промышленная безопасность» 103). Поэтому профессия здесь берётся прямо из рубрики,
-- а не выводится из названия услуги, как у соседа.
-- =============================================================================
CREATE TABLE IF NOT EXISTS site_obuchim.industries (
    id BIGSERIAL PRIMARY KEY,

    -- Таксономия рубрики: cat_rabprof, cat_perepodgotovka, cat_povyshenie и так далее.
    -- Названа зеркально соседней площадке (там obuch-cat), и у каждого типа услуги она
    -- своя; слаги в них повторяются — поэтому ключ составной, а не один слаг.
    taxonomy TEXT NOT NULL,

    -- Идентификатор термина в WordPress. Хранится, чтобы повторный сбор узнавал рубрику
    -- даже после переименования: имя и слаг человек в админке меняет, term_id — нет.
    term_id BIGINT NOT NULL,

    slug TEXT NOT NULL,
    name TEXT NOT NULL,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (taxonomy, term_id)
);


-- =============================================================================
-- Профессия — наша собственная рубрика, дробнее рубрик площадки.
--
-- У этой площадки она совпадает с рубрикой сайта: 184 термина на 1528 услуг — ровно та
-- гранулярность, на которой подбор ссылок под статью перестаёт быть случайным. Разбор
-- названий здесь не нужен и вреден: измерено, что на этих названиях он даёт 953 группы,
-- 820 из которых состоят из одной услуги, а крупнейшие — артефакты вроде
-- «профессиональная инженер».
--
-- Таблица, а не карта в коде, потому что рубрику иногда надо поправить руками: делается это
-- правкой строки, а не новой сборкой.
-- =============================================================================
CREATE TABLE IF NOT EXISTS site_obuchim.professions (
    id BIGSERIAL PRIMARY KEY,

    -- Слаг — слаг термина площадки как есть («apparatchik-avtoklavhiki»): он уже латинский,
    -- и своя транслитерация разошлась бы с тем, что человек видит на сайте.
    slug TEXT NOT NULL UNIQUE,

    -- Имя — имя термина площадки («Слесарь и наладчик»): оно написано людьми и читается
    -- человеком в отчёте.
    name TEXT NOT NULL,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =============================================================================
-- Слово, по которому профессия узнаётся во входных данных статьи.
--
-- Имя рубрики называет одну профессию («Повар») или две через «и» («Слесарь и наладчик»),
-- и каждая даёт свой синоним: иначе половина рубрики осталась бы ненайденной. Таких имён
-- 58 из 184. Колонки professions у задачи этой площадки нет — синонимы работают на тему
-- статьи и на проверку адреса кнопки призыва.
--
-- Уникальность глобальная, а не в пределах профессии: одно слово обязано вести ровно в одну
-- профессию, иначе подбор молча зависел бы от порядка строк.
-- =============================================================================
CREATE TABLE IF NOT EXISTS site_obuchim.profession_aliases (
    id BIGSERIAL PRIMARY KEY,

    profession_id BIGINT NOT NULL REFERENCES site_obuchim.professions(id) ON DELETE CASCADE,

    -- Основа слова в нижнем регистре, уже после нормализации.
    alias TEXT NOT NULL UNIQUE,

    -- Откуда взялась: catalog — разбор названий услуг при сборе, manual — правка человеком.
    -- Нужен затем, чтобы повторный сбор не затирал ручные строки.
    source TEXT NOT NULL DEFAULT 'catalog'
);

CREATE INDEX IF NOT EXISTS idx_profession_aliases_profession
    ON site_obuchim.profession_aliases (profession_id);


-- =============================================================================
-- Услуга площадки. Только услуга: общих и хабовых страниц здесь нет.
--
-- Ключ — идентификатор записи WordPress, а не наш суррогат: второго идентификатора у услуги
-- не существует. Связи related_courses у этой площадки нет — под статьёй стоит карточка
-- призыва, — но каталог нужен перелинковке в тексте и проверке адреса её кнопки.
-- =============================================================================
CREATE TABLE IF NOT EXISTS site_obuchim.programs (
    post_id BIGINT PRIMARY KEY,

    -- Тип записи площадки: rabprof, perepodgotovka, povyshenie, akkreditaciya, medpersonal,
    -- attestaciya.
    post_type TEXT NOT NULL,

    -- Тот же тип человеческими словами («Обучение») и порядок предложения читателю.
    -- Хранятся, а не вычисляются на лету: это решение о том, что показать первым, а не
    -- свойство данных. Рабочие профессии идут первыми — статью про профессию читает тот,
    -- кто входит в неё с нуля.
    category TEXT NOT NULL,
    priority INT NOT NULL,

    slug TEXT NOT NULL,
    url TEXT NOT NULL,

    -- title — заголовок записи целиком, name — короткое название до тире, оно же годится
    -- анкором перелинковки.
    title TEXT NOT NULL,
    name TEXT NOT NULL,

    industry_id BIGINT REFERENCES site_obuchim.industries(id) ON DELETE SET NULL,
    profession_id BIGINT REFERENCES site_obuchim.professions(id) ON DELETE SET NULL,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (post_type, slug)
);

CREATE INDEX IF NOT EXISTS idx_programs_profession ON site_obuchim.programs (profession_id, priority);
CREATE INDEX IF NOT EXISTS idx_programs_industry ON site_obuchim.programs (industry_id, priority);
