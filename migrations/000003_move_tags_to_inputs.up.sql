-- Метки переезжают из ответа модели во входные данные Excel.
--
-- Раньше стадия info генерировала метки вместе с TL;DR и FAQ, а импортёр о них не знал.
-- Это лишняя работа модели и лишняя точка отказа: метки — готовые данные, их задаёт человек
-- в таблице. Теперь они приходят колонкой tags и живут рядом с остальными полями строки
-- Excel, а стадия info отвечает только за TL;DR и FAQ.
--
-- article_metadata.tags удаляется в этой же миграции: писать в неё больше некому, а мёртвых
-- колонок в схеме проекта нет. Уже сгенерированные метки при этом теряются — вернуть их
-- можно только из Excel.

ALTER TABLE article_inputs
    ADD COLUMN tags TEXT;

ALTER TABLE article_metadata
    DROP COLUMN tags;
