-- =============================================================================
-- article_inputs.course_url — адрес курса, на который ведёт кнопка призыва.
--
--   docker exec -i seo-postgres psql -U seo -d seo \
--     -v ON_ERROR_STOP=1 -c 'SET search_path TO obuch_1' -f - \
--     < migrations/obuch_1/000002_course_url.up.sql
--
-- Зачем колонка. Статья блога заканчивается карточкой с кнопкой на программу обучения, и
-- до сих пор адрес называла модель: её просили взять ссылку из перелинковки, а код сверял
-- ответ с каталогом услуг площадки. Кнопка ведёт в деньги, и решать, на какой курс уходит
-- читатель, обязан человек — поэтому адрес приходит книгой, как числа программы у
-- коммерческих страниц.
--
-- Колонка nullable по форме, но обязательна по смыслу: пустое значение роняет статью до
-- первого сообщения модели (obuch1.Flow). NULL здесь означает ровно одно — колонки не было
-- в схеме, когда статью импортировали; такие значения дозаполняет повторный import.
-- =============================================================================

ALTER TABLE article_inputs
    ADD COLUMN IF NOT EXISTS course_url TEXT;

COMMENT ON COLUMN article_inputs.course_url IS
    'Адрес страницы курса для кнопки призыва. Пусто — статья не генерируется.';
