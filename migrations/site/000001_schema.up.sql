-- =============================================================================
-- Схема site — каталог услуг площадки, общий для всех задач.
--
-- ВАЖНО: схема НЕ принадлежит ни одной задаче и применяется руками, как и остальные:
--
--   docker exec -i seo-postgres psql -U seo -d seo -v ON_ERROR_STOP=1 \
--     -f - < migrations/site/000001_schema.up.sql
--
-- Почему отдельная схема, а не таблицы внутри схемы задачи: каталог один на площадку, а
-- repository.ValidateSchema проверяет схемы задач строго в обе стороны — таблица, которой
-- нет в expectedSchema, остановила бы первую же команду задачи. Держать по копии каталога
-- в каждой схеме нельзя тем более: он бы разъехался.
--
-- Что здесь есть и чего нет: это скелет — идентификатор записи, адрес, название, рубрика
-- сайта и наша профессия. Фактов о программе (цена, срок, выдаваемый документ,
-- преподаватель) здесь нет: они снимаются со страниц отдельным медленным проходом и лягут
-- своей миграцией, когда до них дойдут руки.
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS site;


-- =============================================================================
-- Рубрика сайта: то, чем площадка сама разложила свои услуги.
--
-- Приходит полем terms того же wp.getPosts, которым читается каталог, — своей выдумки
-- здесь нет ни одной строки. Рубрики крупные: в «Аппаратчиках и технологических процессах»
-- 218 программ, и подбирать по ним три ссылки под статью бессмысленно. Поэтому рядом живёт
-- своя, дробная разметка (site.professions), а рубрика сайта остаётся вторым кругом:
-- из неё берётся добор, когда своих программ у профессии не хватило.
-- =============================================================================
CREATE TABLE IF NOT EXISTS site.industries (
    id BIGSERIAL PRIMARY KEY,

    -- Таксономия рубрики: obuch-cat, perepod-cat, povysh-cat и так далее. У каждого типа
    -- услуги она своя, и слаги в них повторяются (santehnik есть и в обучении, и в
    -- переподготовке) — поэтому ключ составной, а не один слаг.
    taxonomy TEXT NOT NULL,

    -- Идентификатор термина в WordPress. Хранится, чтобы повторный сбор узнавал рубрику
    -- даже после переименования: имя и слаг человек в админке меняет, term_id — нет.
    term_id BIGINT NOT NULL,

    slug TEXT NOT NULL,
    name TEXT NOT NULL,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (taxonomy, term_id)
);


-- =============================================================================
-- Профессия — наша собственная рубрика, дробнее рубрик площадки.
--
-- Выводится из названия услуги («Сварщик трубопроводов», «Монтажник 5 разряда» → сварщик,
-- монтажник) и потому воспроизводима: повторный сбор даёт тот же разбор. Строк примерно
-- четыре с половиной сотни против сорока семи рубрик обучения — это и есть та
-- гранулярность, на которой подбор трёх ссылок под статью перестаёт быть случайным.
--
-- Таблица, а не карта в коде, именно потому, что разбор кодом неизбежно ошибается на
-- десятках строк из полутора тысяч: исправляется это правкой строки, а не новой сборкой.
-- =============================================================================
CREATE TABLE IF NOT EXISTS site.professions (
    id BIGSERIAL PRIMARY KEY,

    -- Слаг — нормализованная основа слова («svarshhik»), она же ключ разбора.
    slug TEXT NOT NULL UNIQUE,

    -- Имя — самая частая словоформа из названий услуг этой группы («Сварщик»).
    name TEXT NOT NULL,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =============================================================================
-- Слово, по которому профессия узнаётся во входных данных статьи.
--
-- Колонка professions книги импорта заполнена человеком и склоняется как ей вздумается:
-- «сантехник, слесарь, монтажник, трубопроводчик». Сопоставляется она не с названием
-- услуги, а вот с этим списком основ — иначе каждое склонение пришлось бы предусмотреть в
-- запросе.
--
-- Уникальность глобальная, а не в пределах профессии: одно слово обязано вести ровно в одну
-- профессию, иначе подбор молча зависел бы от порядка строк.
-- =============================================================================
CREATE TABLE IF NOT EXISTS site.profession_aliases (
    id BIGSERIAL PRIMARY KEY,

    profession_id BIGINT NOT NULL REFERENCES site.professions(id) ON DELETE CASCADE,

    -- Основа слова в нижнем регистре, уже после нормализации.
    alias TEXT NOT NULL UNIQUE,

    -- Откуда взялась: catalog — разбор названий услуг при сборе, manual — правка человеком.
    -- Нужен затем, чтобы повторный сбор не затирал ручные строки.
    source TEXT NOT NULL DEFAULT 'catalog'
);

CREATE INDEX IF NOT EXISTS idx_profession_aliases_profession
    ON site.profession_aliases (profession_id);


-- =============================================================================
-- Услуга площадки. Только услуга: общих и хабовых страниц здесь нет.
--
-- Ключ — идентификатор записи WordPress, а не наш суррогат: именно он уходит в связь
-- related_courses, и второго идентификатора у услуги не существует.
-- =============================================================================
CREATE TABLE IF NOT EXISTS site.programs (
    post_id BIGINT PRIMARY KEY,

    -- Тип записи площадки: obuch, perepod, povysh, obuch_med, bezopasnost, attestaciya.
    post_type TEXT NOT NULL,

    -- Тот же тип человеческими словами («Обучение») и порядок предложения читателю.
    -- Хранятся, а не вычисляются на лету: это решение о том, что показать первым, а не
    -- свойство данных. Обучение идёт первым — статью про профессию читает тот, кто входит
    -- в неё с нуля.
    category TEXT NOT NULL,
    priority INT NOT NULL,

    slug TEXT NOT NULL,
    url TEXT NOT NULL,

    -- title — заголовок записи целиком, name — короткое название до тире («Сварщик»),
    -- оно же годится анкором перелинковки.
    title TEXT NOT NULL,
    name TEXT NOT NULL,

    industry_id BIGINT REFERENCES site.industries(id) ON DELETE SET NULL,
    profession_id BIGINT REFERENCES site.professions(id) ON DELETE SET NULL,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (post_type, slug)
);

CREATE INDEX IF NOT EXISTS idx_programs_profession ON site.programs (profession_id, priority);
CREATE INDEX IF NOT EXISTS idx_programs_industry ON site.programs (industry_id, priority);
