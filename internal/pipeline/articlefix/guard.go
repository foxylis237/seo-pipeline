package articlefix

import (
	"errors"
	"fmt"
	"regexp"
	"strings"
)

// Пороги предохранителя прогона.
//
// Прогон правки — это десятки статей подряд, и у каждой три попытки провайдера примерно по
// пять минут. Пока отказы единичные, перебор оправдан: длинная или неудачно свёрстанная
// статья не должна останавливать пачку. Но когда отказывает не статья, а провайдер, тот же
// перебор превращается в часы ожидания с заведомо одинаковым исходом — измерено на пачке
// pprof_fix_2: после тридцатой статьи ответы перестали доходить, и каждая следующая статья
// сгорала по пятнадцать минут. Пороги ниже отделяют одно от другого.
const (
	// DefaultSameReasonLimit — сколько подряд статей с одной и той же причиной отказа
	// останавливают прогон. Две: одинаковая формулировка дважды подряд означает, что дело
	// уже не в тексте статьи.
	DefaultSameReasonLimit = 2
	// DefaultFailureLimit — сколько подряд упавших статей останавливают прогон независимо от
	// причин. Три: разные ошибки подряд — тоже признак, что сломалось окружение, а не статья.
	DefaultFailureLimit = 3
)

// ErrRunStopped — прогон остановлен предохранителем, а не дошёл до конца пачки.
//
// Отдельная ошибка, а не строка: вызывающий обязан отличать «пачка пройдена, часть статей
// не удалась» от «пачка брошена на середине». Во втором случае оставшиеся статьи не тронуты
// и ждут следующего запуска — их не пробовали.
var ErrRunStopped = errors.New("прогон остановлен: отказы перестали быть единичными")

// FailureGuard решает, когда прогон пора останавливать.
//
// Счётчика два, и они независимы. Первый — подряд идущие отказы с одинаковой причиной: это
// ловит слёгший провайдер, у которого все статьи падают одним и тем же сообщением после
// одних и тех же повторов. Второй — подряд идущие отказы вообще: ошибки могут быть разными
// (сеть, площадка, модель), а вывод тот же — дальше идти незачем.
//
// Повторы внутри одной статьи предохранитель не считает и считать не должен: их уже
// ограничивает провайдер тремя попытками, и резать их по одинаковости нельзя — «сервер
// занят» дословно повторяется и на третьей попытке часто проходит.
type FailureGuard struct {
	// SameReasonLimit и FailureLimit — пороги; нулевые значения означают умолчания.
	SameReasonLimit int
	FailureLimit    int

	reason     string
	sameReason int
	inARow     int
}

// NewFailureGuard собирает предохранитель с порогами по умолчанию.
func NewFailureGuard() *FailureGuard {
	return &FailureGuard{SameReasonLimit: DefaultSameReasonLimit, FailureLimit: DefaultFailureLimit}
}

// Passed отмечает переписанную статью и снимает накопленное.
//
// Счётчики именно подряд идущие: пачка, где каждая третья статья падает по своей причине,
// прогон останавливать не должна — это её нормальное состояние, а не поломка.
func (g *FailureGuard) Passed() {
	g.reason, g.sameReason, g.inARow = "", 0, 0
}

// Failed регистрирует отказ статьи и отвечает, пора ли останавливать прогон.
//
// nil означает «продолжаем». Непустая ошибка оборачивает ErrRunStopped и годится для показа
// человеку: в ней сказано, какой именно счётчик сработал.
func (g *FailureGuard) Failed(err error) error {
	sameLimit, totalLimit := g.SameReasonLimit, g.FailureLimit
	if sameLimit <= 0 {
		sameLimit = DefaultSameReasonLimit
	}
	if totalLimit <= 0 {
		totalLimit = DefaultFailureLimit
	}
	if reason := failureReason(err); reason == g.reason {
		g.sameReason++
	} else {
		g.reason, g.sameReason = reason, 1
	}
	g.inARow++
	if g.sameReason >= sameLimit {
		// Два %w намеренно: снаружи ошибка обязана опознаваться и как остановка прогона, и
		// как исходная причина отказа — по ней вызывающий решает, что чинить.
		return fmt.Errorf("%w: %d статей подряд упали по одной и той же причине (%w)",
			ErrRunStopped, g.sameReason, err)
	}
	if g.inARow >= totalLimit {
		return fmt.Errorf("%w: %d статей подряд не переписаны", ErrRunStopped, g.inARow)
	}
	return nil
}

var (
	reasonQuotedRE = regexp.MustCompile(`"[^"]*"`)
	reasonNumberRE = regexp.MustCompile(`\d+`)
	reasonSpaceRE  = regexp.MustCompile(`\s+`)
)

// failureReason сводит ошибку к ключу, по которому два отказа считаются одинаковыми.
//
// Это группировка, а не классификация ошибок: решения «повторять ли» по ключу не
// принимаются — повторы уже отработал провайдер, — и разбор по типам здесь ничего не дал бы,
// потому что весь прогон падает одним и тем же типом с разным текстом внутри. Кавычки и
// числа вырезаны намеренно: в них живут имя стадии, идентификатор записи и длительности,
// из-за которых два одинаковых по сути отказа выглядели бы разными.
func failureReason(err error) string {
	text := strings.ToLower(err.Error())
	text = reasonQuotedRE.ReplaceAllString(text, "")
	text = reasonNumberRE.ReplaceAllString(text, "")
	return strings.TrimSpace(reasonSpaceRE.ReplaceAllString(text, " "))
}
