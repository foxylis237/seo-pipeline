package generation

import "testing"

// Запись заголовков приводится к одному виду, и смешанная форма — тоже.
//
// «## H2 - Название» модель пишет, смешивая обе привычные ей формы; до разбора вложенной
// метки к такой строке приписывался второй префикс, и в тексте статьи 2 obuch_1 все
// заголовки стояли как «H2 - H2 - Название».
func TestNormalizeHeadings(t *testing.T) {
	for name, pair := range map[string][2]string{
		"канон остаётся собой":     {"H2 - Название", "H2 - Название"},
		"двоеточие":                {"H2: Название", "H2 - Название"},
		"markdown":                 {"## Название", "H2 - Название"},
		"markdown с жирным":        {"## **Название**", "H2 - Название"},
		"markdown с меткой уровня": {"## H2 - Название", "H2 - Название"},
		"метка уровня под жирным":  {"**H3 - Название**", "H3 - Название"},
		"обычная строка":           {"Просто абзац текста", "Просто абзац текста"},
	} {
		t.Run(name, func(t *testing.T) {
			if got := NormalizeHeadings(pair[0]); got != pair[1] {
				t.Fatalf("%q → %q, ожидалось %q", pair[0], got, pair[1])
			}
		})
	}
}

// Ответ чата структуры несёт лид, строки списков и абзацы; выгружаемому промпту нужны только
// заголовки.
