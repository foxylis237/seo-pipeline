// Package obuch2 задаёт конфигурацию задачи obuch_2 и её поток генерации.
//
// Задача делает то же, что pprof_2, — пишет коммерческие страницы услуг тремя чатами, — но на
// другой площадке. Отличие в этом одном слове и есть причина существования отдельного
// профиля: адрес сайта, его учётные данные, промпты, книга импорта, схема PostgreSQL и
// каталог артефактов у площадок разные, и общий профиль означал бы, что прогон одной задачи
// молча пишет в блог другой.
//
// От pprof_2 пакет не зависит и зависеть не должен — ровно как obuch_1 не зависит от pprof_1.
// Совпадение имён стадий тут случайно и ничего не связывает.
//
// Расходятся задачи не только площадкой. Форму страницы здесь задаёт снятый с живых страниц
// скелет из десяти H2, а не сочинённая моделью структура; числа программы (объём, срок,
// стоимость, документ, аттестация) приходят колонками книги, а не выводятся моделью из вида
// программы; полей ACF у площадки нет вовсе; перелинковки на странице нет ни одной.
package obuch2

import (
	"github.com/foxylis237/seo-pipeline/internal/catalog"
	"github.com/foxylis237/seo-pipeline/internal/tasks"
)

// Имя задачи в двух формах: подчёркнутая идёт в логи, каталоги и схему PostgreSQL,
// дефисная — то, что человек пишет в CLI и в make.
const (
	Name    = "obuch_2"
	Command = "obuch-2"
)

// Имена стадий obuch_2.
//
// Словарь тот же, что у pprof_2: роли стадий совпадают дословно, и второе имя одному и тому
// же понятию завести нельзя — по этим именам раннер сверяет артефакты, а конфигурация
// называет промпты.
const (
	// StageStructure — чат 1: модули, портреты аудитории и формулировки H2 внутри готового
	// скелета страницы. Сам скелет не сочиняется: он зашит в промпт.
	StageStructure = "structure"
	// StageArticle — чат 2, сообщение 1: основной промпт, он же автор страницы.
	//
	// Как и у pprof_2, этот промпт уходит в модель: страницу пишет именно он. Тот же
	// отрендеренный текст сохраняется артефактом и выгружается в Google Docs — второго
	// «базового промпта, который никуда не отправляется» у задачи нет.
	StageArticle = "article"
	// StageReview — чат 2, сообщение 2: редактура возвращает исправленную страницу целиком.
	// Этот текст и есть финальная страница.
	StageReview = "review"
	// StageHTML — чат 3: разметка по вёрстке площадки плюс надпись кнопки заявки.
	// Перелинковки у задачи нет — промпт запрещает любые ссылки внутри текста.
	StageHTML = "html"

	// StageKeywords — резервный подбор исходных запросов для prepare. К генерации страницы
	// отношения не имеет, но схема без него неполна.
	StageKeywords = "keywords"
)

// Stages — стадии, без которых схема obuch_2 неполна.
//
// Набор описывает поток целиком: structure → article → review → html. Из него же строится
// проверка схемы и отчёт dry-run, поэтому лишних имён здесь быть не должно — стадия,
// объявленная без промпта и настроек, обещала бы несуществующее.
//
// Стадии info здесь нет и не появится. Блок частых вопросов остаётся в теле страницы: поля
// FAQ у площадки нет — ни репитера, ни отдельных ключей, — и складывать вопросы некуда.
var Stages = []string{
	StageKeywords, StageStructure, StageArticle, StageReview, StageHTML,
}

// InputColumns — колонки article_inputs, которые есть только в схеме obuch_2.
//
// Базовый набор колонок общий у всех задач — это контракт движка. Здесь перечислено то, что
// нужно именно этой задаче, и заводит их её собственная миграция.
//
// Колонок author, links, professions, tags, teachers, section и service_name здесь нет, и это
// объявление, а не экономия: перелинковки у страницы нет ни одной, меток задача не публикует,
// преподавателей модель придумывает прямо в тексте (связи ACF и типа записи teacher у
// площадки не существует), а раздела каталога и короткого имени услуги никто не читает.
//
//	seo_title        — заголовок для выдачи, отдельный от названия записи;
//	profession       — название профессии, о которой страница;
//	post_type        — тип записи площадки, он же выбирает таксономию рубрики cat_<тип>;
//	hours            — объём программы в академических часах;
//	duration         — срок обучения;
//	price            — стоимость;
//	document         — документ по итогам обучения;
//	attestation      — форма итоговой аттестации;
//	image_source_url — адрес фотографии на стоке, с которой взята обложка.
//
// Пять числовых колонок приходят из книги намеренно: те же значения человек заполняет в полях
// записи руками, и второй источник того же числа разошёлся бы с первым молча — на живых
// страницах площадки они уже разошлись («150 часов» в тексте против «144 часа» в плашке темы).
var InputColumns = []string{
	"seo_title", "profession", "post_type",
	"hours", "duration", "price", "document", "attestation",
	"image_source_url",
}

// Profile возвращает конфигурацию obuch_2.
//
// Overlay пуст: задача DeepSeek-only, второй схемы стадий у неё нет и выбирать не из чего.
func Profile() tasks.Profile {
	return tasks.Profile{
		Name:         Name,
		Command:      Command,
		InputDir:     "input/obuch_2",
		OutputDir:    "tasks/obuch_2/output",
		PromptsDir:   "tasks/obuch_2/prompts",
		TemplatePath: "tasks/obuch_2/templates/result.md.tmpl",
		// Раскладка площадки без ACF для страницы услуги. Без признака задача получила бы
		// блоговую раскладку и отправила бы десяток несуществующих полей темы dpoprof,
		// а запись легла бы обычным post во встроенную рубрику.
		PlainServicePages: true,
		// Блока связанных курсов под страницей услуги нет ни на одной площадке.
		RelatedCourses: false,
		// Своя площадка — свой каталог услуг, в своей схеме PostgreSQL.
		//
		// Признак обязателен, хотя ни перелинковки, ни адреса кнопки у задачи нет. Нулевое
		// значение означает dpoprof, а `make obuch-2 catalog-sync` начинается с удаления всех
		// услуг схемы: с пустым признаком он стёр бы каталог соседней площадки и залил бы в
		// её схему чужие услуги. Отсюда же раскладка публикации берёт список типов записей и
		// правило имени таксономии — cat_<тип>, зеркально соседу.
		CatalogSite:      catalog.SiteObuchim,
		LLMConfigPath:    "config/obuch_2.yaml",
		LLMOverlayPath:   "",
		ImportReportsDir: "output/obuch_2/import-reports",
		DiagnosticsDir:   "output/obuch_2/debug",
		DBSchema:         Name,
		EnvPrefix:        "OBUCH_2_",
		// Папка Drive не заведена, и потому выгрузка промптов выключена в config/obuch_2.yaml.
		// Общей с pprof_2 она быть не может: документ ищется по имени «Промт: <заголовок>», а
		// названия страниц услуг у задач совпадают — одна папка на двоих означала бы
		// перезапись чужого промпта.
		GoogleFolderURL:   "",
		ExtraInputColumns: InputColumns,
		// Стадии info у задачи нет: TL;DR, времени чтения и отдельного блока вопросов она не
		// генерирует. Без признака раннер полного прогона ждал бы метаданных вечно и
		// возвращал бы страницу на этап article.
		WithoutMetadataStage: true,
		// MetadataFAQOnly остаётся нулевым, и это решение. Признак поднял бы требование
		// непустого FAQ на публикации, а заполнять его нечем: вопросы остаются в теле
		// страницы, потому что поля под них у площадки нет. Цена решения — колонка
		// article_metadata.tldr в схеме задачи, в которую никто не пишет: этот же признак
		// сегодня решает, есть ли колонка (repository.SchemaProfile.WithoutTLDR).
		MetadataFAQOnly: false,
		LLMStages:       Stages,
	}
}
