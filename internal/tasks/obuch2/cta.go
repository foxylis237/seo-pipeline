// buildCTACard собирает карточку из разобранных строк.
//
// Второе значение — список ключей, которых модель не назвала и которые пришлось заменить
// умолчанием. Отсутствие строки стадию не роняет: за генерацию уже заплачено, и страница с
// типовой карточкой полезнее отказа, — но уходит в лог: по нему видно, что доспрос не
// сработал. Список сортируется, чтобы предупреждение не плясало от прогона к прогону.
func buildCTACard(slots map[string][]string) (ctaCard, []string) {
	card := defaultCTACard()
	targets := map[string]*string{
		"заголовок": &card.Heading,
		"описание":  &card.Intro,
		"кнопка":    &card.ButtonText,
	}
	var missing []string
	for key, target := range targets {
		values, ok := slots[key]
		if !ok || len(values) == 0 {
			missing = append(missing, key)
			continue
		}
		*target = html.EscapeString(values[0])
	}
	if documents := ctaDocuments(slots["документ"]); len(documents) > 0 {
		card.Documents = documents
	} else {
		missing = append(missing, "документ")
	}
	sort.Strings(missing)
	return card, missing
}

// ctaDocuments разбирает строки документов: «ярлык — пояснение».
//
// Строка без тире пропускается: ярлык без пояснения верстается жирной строкой без текста, и
// в блоге это выглядит обрывом. Пустой результат означает «модель не назвала ни одного» — и
// список берётся из умолчаний целиком, а не наполовину.
func ctaDocuments(values []string) []ctaDocument {
	documents := make([]ctaDocument, 0, len(values))
	for _, value := range values {
		label, text, found := strings.Cut(value, "—")
		if !found {
			label, text, found = strings.Cut(value, " - ")
		}
		label, text = strings.TrimSpace(label), strings.TrimSpace(text)
		if !found || label == "" || text == "" {
			continue
		}
		documents = append(documents, ctaDocument{
			Label: html.EscapeString(label), Text: html.EscapeString(text),
		})
	}
	return documents
}

// renderCTACard подставляет строки в шаблон.
func renderCTACard(tmpl *template.Template, card ctaCard) (string, error) {
	var out strings.Builder
	if err := tmpl.Execute(&out, card); err != nil {
		return "", fmt.Errorf("карточка призыва не собрана: %w", err)
	}
	return strings.TrimSpace(out.String()), nil
}

// appendCTACard дописывает карточку в конец разметки и говорит, добавил ли.
//
// Если призыв в разметке уже есть, своя карточка не дописывается: двух подряд быть не должно,
// а нарисованный моделью всё же стоит на своём месте.
func appendCTACard(markup, card string) (string, bool) {
	lower := strings.ToLower(markup)
	for _, marker := range []string{ctaCardMarker, ctaButtonMarker, ctaTagMarker} {
		if strings.Contains(lower, marker) {
			return markup, false
		}
	}
	return strings.TrimSpace(markup) + "\n\n" + card, true
}
