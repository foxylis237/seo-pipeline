// CTACardPath — шаблон карточки призыва, последнего элемента размеченной страницы.
//
// Карточку ставит код, а не модель: у неё фиксированная вёрстка с инлайновыми стилями, снятая
// с живых страниц площадки, — модель воспроизводила бы её каждый раз по-своему, а место в
// ответе она занимает наравне с текстом, который и без того упирается в предел длины
// сообщения. У модели спрашиваются только пять строк текста внутри карточки.
//
// Карточка — единственное место в теле страницы, где инлайновый стиль на этой площадке
// законен помимо оформления блоков: всё остальное несут классы темы.
//
// Путь относителен корня проекта, как и остальные пути задачи (PromptsDir, TemplatePath).
const CTACardPath = "tasks/obuch_2/templates/cta_card.html"

// Признаки уже нарисованного призыва. Промпт карточку и тег button запрещает, но если модель
// всё же нарисовала свой призыв, второго быть не должно: разбираться с ним человеку.
//
// Классов два, потому что модель воспроизводит вёрстку по-разному: карточку целиком или одну
// кнопку. Третий признак — сам тег: он остался от прежней плоской кнопки и стоит дёшево.
// Вёрстка снята с живых страниц услуг площадки (бетонщики-арматурщики, гид-переводчик):
// простой <div> и одна оранжевая кнопка. Прежней карточки sp-cta-card на страницах услуг нет
// ни одной — она пришла из блога, и здесь была чужой.
const (
	ctaCardMarker   = "feedback__event"
	ctaButtonMarker = "btn-primary"
	ctaTagMarker    = "<button"
)

// ctaCard — слоты шаблона карточки. Имя поля совпадает с плейсхолдером файла: разойдутся —
// шаблон подставит пустую строку, а не откажет, поэтому набор проверяется тестом.
//
// Адреса среди слотов нет вовсе, в отличие от карточки obuch_1: кнопка открывает форму заявки,
// а не ведёт на страницу программы. Отсюда же и тег — button, а не ссылка, и класс service,
// за который цепляется скрипт формы площадки.
type ctaCard struct {
	Heading    string
	Intro      string
	Documents  []ctaDocument
	ButtonText string
}

// ctaDocument — строка списка документов: жирный ярлык и пояснение за тире. Разделены, а не
// одной строкой, потому что вёрстка площадки жирнит ровно ярлык.
type ctaDocument struct {
	Label string
	Text  string
}

// readCTACard читает и разбирает шаблон карточки.
//
// Разбирается он до первого сообщения модели: отказ файла обязан стоить нисколько, а не
// оплаченный ответ разметки. Пустой файл — тоже отказ: страница заканчивается абзацем
// призыва, за которым читателю некуда нажать.
func readCTACard(path string) (*template.Template, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("шаблон карточки призыва не прочитан (%s): %w", path, err)
	}
	if strings.TrimSpace(string(raw)) == "" {
		return nil, fmt.Errorf("файл карточки призыва пуст: %s", path)
	}
	parsed, err := template.New("cta").Parse(string(raw))
	if err != nil {
		return nil, fmt.Errorf("шаблон карточки призыва не разобран (%s): %w", path, err)
	}
	return parsed, nil
}

