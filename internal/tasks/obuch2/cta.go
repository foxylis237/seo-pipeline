// ctaNumberingRE — нумерация и маркер списка в начале строки: «1. », «2) », «- », «• ».
// Модель добавляет их к ответу сама, и ключ из-за них перестаёт узнаваться.
var ctaNumberingRE = regexp.MustCompile(`^(?:[-*•]\s*)?(?:\d+[.)]\s*)?`)

// ctaSlotKeys — закрытый набор ключей. Чужой ключ — не ошибка, а болтовня модели вокруг
// ответа, и молча пропустить его дешевле, чем уронить оплаченную разметку.
var ctaSlotKeys = map[string]struct{}{
	"заголовок": {}, "описание": {}, "документ": {}, "кнопка": {},
}

// ctaRepeatedSlots — ключи, которые приходят несколькими строками. Остальные перетирать
// нельзя: модель иногда дописывает «а лучше так», и первым идёт то, о чём её просили.
var ctaRepeatedSlots = map[string]struct{}{"документ": {}}

// parseCTASlots разбирает ответ модели построчно.
//
// Строка без разделителя, с чужим ключом или с пустым значением пропускается молча: модель
// добавляет к ответу нумерацию, вступление и кодовую обёртку. Повтор ключа не перетирает
// первое значение: модель иногда дописывает «а лучше так», и первым идёт то, о чём её
// просили.
func parseCTASlots(answer string) map[string][]string {
	slots := make(map[string][]string, len(ctaSlotKeys))
	for _, line := range strings.Split(answer, "\n") {
		line = strings.TrimSpace(strings.ReplaceAll(line, "`", ""))
		key, value, found := strings.Cut(line, ";;")
		if !found {
			continue
		}
		key = strings.ToLower(strings.TrimSpace(ctaNumberingRE.ReplaceAllString(strings.TrimSpace(key), "")))
		value = strings.TrimSpace(value)
		if _, known := ctaSlotKeys[key]; !known || value == "" {
			continue
		}
		if _, repeated := ctaRepeatedSlots[key]; !repeated && len(slots[key]) > 0 {
			continue
		}
		slots[key] = append(slots[key], value)
	}
	return slots
}

