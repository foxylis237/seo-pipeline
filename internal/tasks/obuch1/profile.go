// Package obuch1 задаёт конфигурацию задачи obuch_1.
//
// Задача делает то же, что pprof_1, — пишет статьи блога тремя чатами, — но на другой
// площадке. Отличие в этом одном слове и есть причина существования отдельного профиля:
// адрес сайта, его учётные данные, промпты, книга импорта, схема PostgreSQL и каталог
// артефактов у площадок разные, и общий профиль означал бы, что прогон одной задачи молча
// пишет в блог другой.
//
// Поток генерации у задачи свой (flow.go), хотя порядок чатов и имена стадий те же, что у
// pprof_1. Расходится третий чат: у площадки другая вёрстка — классы темы вместо инлайновых
// стилей — и под статьёй стоит карточка призыва, которой у pprof_1 нет вовсе. Общий поток на
// две площадки означал бы признак внутри чистки разметки, а править работающий поток соседа
// ради новой задачи нельзя.
//
// Как работает пайплайн вообще — знает internal/pipeline. Здесь только то, чем задача
// отличается: где лежат её файлы и в каком порядке идут её стадии.
package obuch1

import "github.com/foxylis237/seo-pipeline/internal/tasks"

// Имя задачи в двух формах: подчёркнутая идёт в логи, каталоги и схему PostgreSQL,
// дефисная — то, что человек пишет в CLI и в make.
const (
	Name    = "obuch_1"
	Command = "obuch-1"
)

// Имена стадий obuch_1.
//
// Словарь тот же, что у pprof_1: роли стадий совпадают дословно, и второе имя одному и тому
// же понятию завести нельзя — по этим именам раннер сверяет артефакты, а конфигурация
// называет промпты.
const (
	StageStructure = "structure"
	StageExpert    = "expert"
	StageReview    = "review"
	StageInfo      = "info"
	StageHTML      = "html"

	// StageArticle — базовый промпт статьи. В LLM он не уходит: стадия существует только
	// чтобы собрать промпт из входных данных и research, сохранить его артефактом и отдать
	// в выгрузку. Текст статьи пишет StageExpert.
	StageArticle = "article"

	// StageKeywords — резервный подбор исходных запросов для prepare. К генерации статьи
	// отношения не имеет, но схема без него неполна.
	StageKeywords = "keywords"
)

// Stages — стадии, без которых схема obuch_1 неполна.
var Stages = []string{
	StageKeywords, StageStructure, StageArticle,
	StageExpert, StageReview, StageInfo, StageHTML,
}

// RegulationDir — каталог регламента статьи. Тот же путь называет схема стадий: документ
// прикрепляют structure и expert, и каталог у них один.
//
// Каталог, а не файл: имя регламента не фиксируется, его выбирает
// config.ResolveStageAttachments — ровно один документ в каталоге. Пустой каталог роняет
// стадию до обращения к модели.
//
// Регламент вёрстки документом не заводится: вёрстка площадки короче регламента соседней
// задачи и целиком живёт в промпте tasks/obuch_1/prompts/4_html.txt. Второе описание того же
// самого разошлось бы с первым молча, и стадия html документов не получает вовсе.
const RegulationDir = "input/obuch_1/regulations/article"

// Profile возвращает конфигурацию obuch_1.
//
// Overlay пуст: задача DeepSeek-only, второй схемы стадий у неё нет.
func Profile() tasks.Profile {
	return tasks.Profile{
		Name:         Name,
		Command:      Command,
		InputDir:     "input/obuch_1",
		OutputDir:    "tasks/obuch_1/output",
		PromptsDir:   "tasks/obuch_1/prompts",
		TemplatePath: "tasks/obuch_1/templates/result.md.tmpl",
		// Блок связанных курсов выключен, и это решение, а не пропуск: каталог услуг живёт
		// в схеме site и описывает одну площадку — ту, для которой его собирает catalog-sync.
		// Включить признак здесь значило бы подставить под статьи нового сайта карточки
		// чужих программ. Появится каталог этой площадки — признак включается тут.
		RelatedCourses: false,
		// У площадки нет ни одного поля ACF: в запись уходят рубрика, метки, ярлык, обложка,
		// тело и три ключа Yoast. Без признака задача получила бы блоговую раскладку и
		// отправила бы десяток несуществующих полей, включая связь с типом записи `author`,
		// которого на площадке тоже нет.
		PlainBlogPages: true,
		// Каталог услуг в схеме site собран для dpoprof, а у этой задачи своя площадка.
		// Признак закрывает ей команды каталога: `catalog-sync` начинается с удаления всех
		// услуг, и один запуск отсюда стёр бы каталог соседей вместе с их подбором курсов.
		WithoutSiteCatalog: true,
		LLMConfigPath:      "config/obuch_1.yaml",
		LLMOverlayPath:     "",
		ImportReportsDir:   "output/obuch_1/import-reports",
		DiagnosticsDir:     "output/obuch_1/debug",
		DBSchema:           Name,
		EnvPrefix:          "OBUCH_1_",
		// Папка Google Drive своя, но выгрузка пока выключена секцией pipeline конфига:
		// документ ищется по имени «Промт: <заголовок>», а заголовки статей этой задачи
		// совпадают с заголовками pprof_1, и общая папка означала бы перезапись чужого
		// промпта. Появится своя папка — сюда её адрес, и выгрузку можно включать.
		GoogleFolderURL: "",
		// Колонок меньше, чем у pprof_1, и это объявление, а не экономия.
		//
		// author не заводится: типа записи `author` у площадки нет вовсе — автором статьи
		// становится учётная запись, под которой мы публикуем, и связывать не с чем.
		// professions не заводится: её читал только подбор связанных курсов, а блока под
		// статьёй у темы нет (RelatedCourses false). Колонка, которую никто не читает, —
		// обещание раздела, которого не будет.
		//
		// Остаются три: links — адреса программ для перелинковки внутри текста;
		// seo_title — короткий заголовок выдачи (_yoast_wpseo_title), у площадки Yoast
		// Premium; tags — метки, которые на площадке не ставят и ставим мы.
		ExtraInputColumns: []string{"links", "seo_title", "tags"},
		LLMStages:         Stages,
	}
}
