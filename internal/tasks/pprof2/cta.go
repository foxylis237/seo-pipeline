package pprof2

import (
	"fmt"
	"os"
	"strings"
)

// CTAButtonPath — файл кнопки заявки, которой заканчивается размеченная страница.
//
// Кнопка — оформление сайта, а не текст страницы: у неё фиксированная разметка, инлайновые
// стили и класс, за который цепляется скрипт формы. Модель воспроизводила бы её каждый раз
// заново — с другими пробелами, сокращённым style и потерянным data-popup, — а место в
// ответе она занимает наравне с текстом, который и без того упирается в предел длины
// сообщения. Поэтому кнопку ставит код после вёрстки, промпт html о ней не знает, и менять
// её — значит править этот файл.
//
// Путь относителен корня проекта, как и остальные пути задачи (PromptsDir, TemplatePath).
const CTAButtonPath = "tasks/pprof_2/templates/cta_button.html"

// readCTAButton читает кнопку с диска.
//
// Спрашивается она до первого сообщения модели: без кнопки страница неполна, а узнать об этом
// после оплаченной разметки — значит выбросить ответ. Пустой файл — тоже отказ: молча
// опубликованная страница без кнопки хуже понятной остановки стадии.
func readCTAButton(path string) (string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return "", fmt.Errorf("кнопка заявки не прочитана (%s): %w", path, err)
	}
	button := strings.TrimSpace(string(raw))
	if button == "" {
		return "", fmt.Errorf("файл кнопки заявки пуст: %s", path)
	}
	return button, nil
}

// appendCTAButton дописывает кнопку в конец разметки и говорит, добавил ли.
//
// Свою кнопку разметка содержать не должна — промпт html запрещает тег button, — но если она
// всё же пришла, второй не появляется: две кнопки подряд на странице заметнее, чем чужая
// вёрстка одной, и разбираться с ней всё равно человеку.
func appendCTAButton(markup, button string) (string, bool) {
	if strings.Contains(strings.ToLower(markup), "<button") {
		return markup, false
	}
	return strings.TrimSpace(markup) + "\n\n" + button, true
}
