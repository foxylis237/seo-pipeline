// Package tasks описывает профиль задачи — всё, чем один пайплайн отличается от другого.
//
// Здесь живёт только тип. Значения задают пакеты самих задач (internal/tasks/task1,
// internal/tasks/pprof1), а собирает их в реестр composition root. Наружу из него уходят
// конкретные значения: путь, каталог, DSN. Ни один пакет движка (internal/pipeline) и ни одна
// интеграция профиль не принимают и о существовании задач не знают — иначе Profile превратился
// бы в service locator, а граница между задачей и движком исчезла бы.
package tasks

import "path/filepath"

// CommonPromptsDir — каталог промптов, общих для всех задач.
//
// Сюда попадает то, что принадлежит не задаче, а операции: DEMO собирается у task_1 и
// pprof_1 одним и тем же кодом и одними и теми же промптами, поэтому и файл у них один.
// Копия в дереве каждой задачи означала бы два текста, которые обязаны совпадать, но
// расходятся молча.
const CommonPromptsDir = "tasks/common/prompts"

// Profile — полный набор того, что задача не делит с другими задачами.
//
// Поля намеренно перечислены явно, а не выводятся из Name: имена каталогов исторические
// (`output/task1` при задаче `task_1`), и вычисление по имени сделало бы разведение путей
// невозможным без правки движка.
type Profile struct {
	// Name — подчёркнутая форма (task_1). Идёт в логи как поле task.
	Name string
	// Command — дефисная форма (task-1). Это первый аргумент CLI и цель Makefile.
	Command string

	// InputDir — каталог с Excel исходных статей. Именно каталог, а не файл: имя книги
	// задача не фиксирует, её выбирает importer.ResolveWorkbook. Каталоги у задач разные —
	// один файл на двоих означал бы, что смена входных данных одной задачи молча меняет
	// импорт другой.
	InputDir string
	// OutputDir — корень артефактов статей, он же OUTPUT_DIR.
	OutputDir string
	// PromptsDir — каталог промптов задачи. Сами пути к промптам перечислены в LLM-конфиге;
	// здесь корень нужен тем частям, которые собирают путь сами. Промпты, общие у задач,
	// сюда не попадают — им отведён CommonPromptsDir.
	PromptsDir string
	// TemplatePath — шаблон result.md.
	TemplatePath string
	// LLMConfigPath и LLMOverlayPath — базовая схема стадий и наложение. Пустой overlay
	// означает, что у задачи одна схема и выбирать не из чего.
	LLMConfigPath  string
	LLMOverlayPath string
	// ImportReportsDir — отчёты импорта, лежат вне OutputDir.
	ImportReportsDir string
	// DiagnosticsDir — корень диагностики браузерных интеграций. Подкаталог сервиса выдаёт
	// DiagnosticsSubdir: сами интеграции про задачи не знают.
	DiagnosticsDir string
	// DBSchema — схема PostgreSQL. Изоляция задач в базе держится только на ней.
	DBSchema string
	// EnvPrefix — префикс переменных окружения, которыми профиль можно переопределить.
	// Пустой у task_1: у него исторические имена без префикса, и менять их нельзя.
	EnvPrefix string
	// GoogleFolderURL — папка Google Drive, в которой живут документы промптов этой задачи.
	// Пустая означает общую папку по умолчанию из пакета интеграции: так у task_1 и pprof_1
	// сохраняется тот же адрес, что был до появления настройки. Папки у задач разные не ради
	// порядка, а ради изоляции: документ ищется по имени, а имена статей разных задач
	// совпадают, и одна папка на двоих означала бы перезапись чужого промпта.
	GoogleFolderURL string
	// ExtraInputColumns — колонки article_inputs, которые есть только в схеме этой задачи.
	//
	// Базовый набор колонок — контракт движка, он одинаков у всех задач. Всё, что нужно одной
	// задаче и не нужно остальным, перечисляется здесь и заводится её собственной миграцией:
	// так поля pprof_2 не попадают в таблицы pprof_1, а проверка схемы знает, чего ждать в
	// каждой из них. Имена сверяются с реестром репозитория, опечатка роняет команду на старте.
	ExtraInputColumns []string
	// WithoutMetadataStage объявляет, что поток задачи не пишет article_metadata — у неё нет
	// стадии, которая генерирует TL;DR и FAQ.
	//
	// Нулевое значение означает «стадия есть»: это поведение, которое было до появления задач
	// без неё. Признак нужен раннеру полного прогона — он считает этап article завершённым по
	// сохранённым артефактам, и у задачи без метаданных ждал бы их бесконечно.
	WithoutMetadataStage bool
	// MetadataFAQOnly объявляет, что из разделов стадии info задача даёт только FAQ.
	//
	// Признак нужен публикации: TL;DR и время чтения она требует у задачи со стадией info и
	// не требует у задачи без неё, а pprof_2 не подходит ни под одно — FAQ у него есть, но
	// вынут из текста страницы, а TL;DR и времени чтения нет. Нулевое значение — прежнее
	// поведение: набор разделов определяется одним WithoutMetadataStage.
	//
	// Раннер полного прогона признак не читает: для него FAQ остаётся необязательным, иначе
	// страница без блока частых вопросов вечно возвращалась бы на этап article.
	MetadataFAQOnly bool
	// CommercialPages объявляет, что задача публикует коммерческие страницы услуг, а не
	// статьи блога.
	//
	// Признак читает только публикация: сценарий у неё общий, а раскладка данных по полям
	// площадки — своя. У статьи блога это поля темы (prof_title, blog_faq) и встроенные
	// рубрики с метками; у страницы услуги — своя таксономия, поля ACF и связь с записью
	// преподавателя. Нулевое значение — прежнее поведение, раскладка статьи блога.
	//
	// Ни движок, ни стадии генерации признак не спрашивают: чем задача пишет текст, он не
	// определяет.
	CommercialPages bool
	// ArticleFix — настройки задачи, которая правит уже опубликованные статьи.
	//
	// nil означает «задача пишет статью, а не правит» — так у task_1, pprof_1 и pprof_2.
	// Непустое поле уводит задачу на поток internal/pipeline/articlefix и заодно снимает с
	// неё проверку схемы движка: таблиц article_inputs и article_metadata у задач правки нет
	// по замыслу. Признак живёт в профиле, а не в switch по имени задачи: пятая задача правки
	// добавляется своим пакетом и строкой реестра, не трогая composition root.
	ArticleFix *ArticleFix
	// LLMStages — стадии, без которых схема задачи неполна. Набор у задач разный: task_1
	// генерирует статью шестью стадиями, pprof_1 — своими. Валидация конфигурации сверяется
	// с этим списком, а не с общим на весь проект.
	LLMStages []string
}

// ArticleFix — то, чем одна задача правки отличается от другой.
//
// Пути к двум файлам плюс признак: сам поток правки у задач общий. Промпт говорит модели,
// что менять в статье; правило переименования — что делать с её заголовком. Каталоги, схема
// PostgreSQL и схема стадий приходят из общих полей профиля, как и у задач генерации.
type ArticleFix struct {
	// RewritePromptPath — регламент правки. Тот же файл называет схема стадий задачи:
	// путь нужен и сборке промпта, поэтому имя одно на оба места.
	RewritePromptPath string
	// TextUnchanged — «текст не трогать»: задача меняет только заголовок, к модели не ходит.
	//
	// Переходное состояние задачи, у которой переименование уже согласовано, а регламент
	// правок ещё пишется: промпт на диске лежит черновиком и в модель не уходит. Снимается
	// вместе с готовым промптом — так у pprof_fix_4.
	TextUnchanged bool
	// HeadingsRewritten объявляет, что промпт задачи переписывает заголовки разделов.
	//
	// Нулевое значение — прежнее поведение: обрыв ответа ловится дословной сверкой
	// последнего заголовка статьи, и промпт менять структуру не вправе. Задача, которая
	// переводит страницу на другую услугу (pprof_fix_5 — на НМО), заголовки меняет по
	// заданию, и дословная сверка объявляла бы обрывом каждую статью; поток переходит на
	// структурный признак — articlefix.RewriteHeadings.
	HeadingsRewritten bool
	// TitleRulePath — файл с примером переименования, парой «было — стало».
	//
	// Пустое значение означает «заголовок не трогать» — так у pprof_fix_3, который правит
	// только текст. Это решение задачи, а не пропуск: composition root подставляет вместо
	// файла articlefix.KeepTitle, и поток идёт тот же самый.
	TitleRulePath string
}

// DiagnosticsSubdir возвращает корень диагностики одного сервиса.
//
// Интеграции получают уже готовый путь и остаются task-agnostic: в них не должно быть ни
// имени задачи, ни знания о том, что задач больше одной.
func (p Profile) DiagnosticsSubdir(service string) string {
	return filepath.Join(p.DiagnosticsDir, service)
}
